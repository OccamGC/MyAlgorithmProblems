// Codex (GPT-6): generate the problem setter's prefix table by pruning invalid low digits.
// Compile as C++17; stdout is a complete prefix-table.hpp file.
#include <algorithm>
#include <cstdint>
#include <iostream>
#include <vector>

std::vector<std::uint32_t> Valid;
std::uint32_t Powers[30];

void Enumerate(int Position, std::uint32_t Mask, std::uint32_t Decimal)
{
	if (Position == 30)
	{
		Valid.push_back(Mask);
		return;
	}
	Enumerate(Position + 1, Mask, Decimal);
	std::uint32_t Next = Decimal + Powers[Position];
	if ((Next >> Position) & 1u)
	{
		Enumerate(Position + 1, Mask | (1u << Position), Next);
	}
}

int main()
{
	Powers[0] = 1;
	for (int i = 1; i < 30; ++i)
	{
		Powers[i] = Powers[i - 1] * 10u;
	}
	Enumerate(0, 0, 0);
	std::sort(Valid.begin(), Valid.end());
	constexpr std::uint32_t BlockSize = 160000;
	constexpr std::uint32_t Limit = (1u << 30) - 1;
	constexpr int Count = Limit / BlockSize + 2;
	std::cout << "// Generated by tests/generate-table.cpp; includes zero.\n#pragma once\n#include <array>\n#include <cstdint>\n\ninline constexpr std::array<std::uint32_t, " << Count << "> PrefixCount = {\n";
	std::size_t Index = 0;
	for (int Block = 0; Block < Count; ++Block)
	{
		while (Index < Valid.size() && Valid[Index] <= std::min(Block * BlockSize, Limit))
		{
			++Index;
		}
		if (Block % 12 == 0)
		{
			std::cout << '\t';
		}
		std::cout << Index;
		if (Block + 1 != Count)
		{
			std::cout << ',';
		}
		if (Block % 12 == 11 || Block + 1 == Count)
		{
			std::cout << '\n';
		}
	}
	std::cout << "};\n";
}
