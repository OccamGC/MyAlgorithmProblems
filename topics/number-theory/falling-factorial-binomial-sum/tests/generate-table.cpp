// Codex (GPT-6): reproducible factorial checkpoints for the fixed modulus.
// Prints factorial-table.hpp to standard output. About one billion products.
#include <cstdio>

int main()
{
	constexpr long long Mod = 1000000007;
	constexpr int Step = 1000000;
	std::puts("// Generated by tests/generate-table.cpp; checkpoint j stores (1000000*j)!.");
	std::puts("#ifndef FACTORIAL_TABLE_HPP\n#define FACTORIAL_TABLE_HPP");
	std::puts("constexpr int CheckpointStep = 1000000;");
	std::puts("constexpr int FactorialCheckpoint[] =\n{\n\t1,");
	long long Product = 1;
	for (int i = 1; i < Mod; ++i)
	{
		Product = Product * i % Mod;
		if (i % Step == 0)
		{
			std::printf("\t%lld,\n", Product);
		}
	}
	std::puts("};\n#endif");
	return Product == Mod - 1 ? 0 : 1;
}
